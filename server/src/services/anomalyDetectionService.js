const SYSTEM_VERIFICATION_PROMPT = `You are the AI Verification & Review Assistant for FarmDirect.
Your role is to explain structured anomaly detection flags generated by our rule-based system.
You MUST:
1. Use ONLY the supplied structured flags and evidence.
2. Never invent certifications (e.g. organic, chemical-free, lab-tested, government-certified).
3. Never accuse the farmer or product of "fraud", "scam", or being "fake".
4. Use objective, neutral language (e.g., "Potential anomaly", "Information inconsistency", "Review recommended").
5. If evidence is insufficient for any determination, clearly state: "Insufficient evidence for a reliable determination."
6. Provide a concise summary and clear human review recommendations.
7. Return clean JSON containing "summary" and "recommendations" (array of strings).`;

/**
 * Calls Gemini if configured, with safety controls.
 */
async function callGeminiVerificationIfConfigured(flags) {
  if (!env.AI_API_KEY || !env.AI_API_KEY.trim()) {
    return null;
  }

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 8000);

  try {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${encodeURIComponent(env.AI_API_KEY)}`;
    const prompt = `Review the following structured anomaly flags and generate a human-readable review explanation:
Flags:
${JSON.stringify(flags, null, 2)}

Provide your response in JSON format with two keys:
"summary": "Short 1-3 sentence summary of detected flags",
"recommendations": ["Array of specific action items for the farmer/reviewer to verify"]`;

    const response = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      signal: controller.signal,
      body: JSON.stringify({
        contents: [
          {
            role: 'user',
            parts: [{ text: `${SYSTEM_VERIFICATION_PROMPT}\n\n${prompt}` }]
          }
        ],
        generationConfig: {
          temperature: 0.1,
          maxOutputTokens: 400,
          responseMimeType: 'application/json'
        }
      })
    });

    clearTimeout(timeoutId);

    if (!response.ok) {
      return null;
    }

    const data = await response.json();
    const candidate = data?.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!candidate) return null;

    const cleaned = candidate.replace(/```json\n?|\n?```/g, '').trim();
    const parsed = JSON.parse(cleaned);
    if (parsed && typeof parsed.summary === 'string' && Array.isArray(parsed.recommendations)) {
      return parsed;
    }
    return null;
  } catch {
    clearTimeout(timeoutId);
    return null;
  }
}

/**
 * 1. Price Anomaly Detector
 * Compares product price with active products in same category/unit using real MySQL data.
 * Thresholds:
 * - LOW: 30-50% deviation
 * - MEDIUM: 50-100% deviation
 * - HIGH: >100% deviation
 * Avoids false positives if fewer than 2 comparable products exist.
 */
export function detectPriceAnomaly(product, comparableProducts = []) {
  if (!product || typeof product.price !== 'number' || product.price <= 0) {
    return null;
  }

  // Filter comparable products: same category, active, positive price, exclude self
  const validComparables = comparableProducts.filter((p) => {
    if (!p || p.id === product.id) return false;
    if (p.status !== 'ACTIVE') return false;
    if (typeof p.price !== 'number' || p.price <= 0) return false;

    const sameCat = (p.category || '').trim().toLowerCase() === (product.category || '').trim().toLowerCase();
    if (!sameCat) return false;

    return true;
  });

  // Check if we have subset with matching unit for higher precision
  let matchedComparables = validComparables;
  if (product.unit) {
    const sameUnitComparables = validComparables.filter(
      (p) => (p.unit || '').trim().toLowerCase() === (product.unit || '').trim().toLowerCase()
    );
    if (sameUnitComparables.length >= 2) {
      matchedComparables = sameUnitComparables;
    }
  }

  // Avoid false positives if insufficient comparable sample
  if (matchedComparables.length < 2) {
    return null;
  }

  const sum = matchedComparables.reduce((acc, curr) => acc + curr.price, 0);
  const avgPrice = sum / matchedComparables.length;
  const deviation = Math.abs(product.price - avgPrice);
  const deviationPercent = Math.round((deviation / avgPrice) * 100);

  let severity = null;
  if (deviationPercent > 100) {
    severity = 'HIGH';
  } else if (deviationPercent >= 50) {
    severity = 'MEDIUM';
  } else if (deviationPercent >= 30) {
    severity = 'LOW';
  }

  if (!severity) {
    return null;
  }

  const direction = product.price > avgPrice ? 'higher than' : 'lower than';
  const confidence = Number(Math.min(0.95, 0.70 + (matchedComparables.length * 0.05)).toFixed(2));

  return {
    type: 'PRICE_ANOMALY',
    severity,
    title: 'Potential price anomaly',
    message: `Product price is significantly ${direction} comparable products in the ${product.category} category.`,
    evidence: {
      productPrice: product.price,
      comparableAverage: Math.round(avgPrice * 100) / 100,
      deviationPercent,
      sampleSize: matchedComparables.length,
      unit: product.unit || 'unit'
    },
    recommendation: 'Review product pricing compared to similar category items.',
    confidence
  };
}

/**
 * 2. Transparency Anomaly Detector
 * Checks for missing required transparency fields.
 * Differentiates MISSING fields (TRANSPARENCY_INCOMPLETE) from INCONSISTENT dates.
 */
export function detectTransparencyAnomaly(product) {
  const flags = [];
  if (!product) return flags;

  const transparency = product.transparency || {};

  const harvestDate = transparency.harvestDate || product.harvestDate;
  const expiryDate = transparency.expiryDate || product.expiryDate;
  const origin = transparency.origin || product.origin || product.location;
  const batchNumber = transparency.batchNumber || product.batchNumber;
  const ingredients = transparency.ingredients || product.ingredients;

  if (!harvestDate) {
    flags.push({
      type: 'TRANSPARENCY_INCOMPLETE',
      severity: 'LOW',
      title: 'Missing harvest date',
      message: 'Harvest date has not been provided.',
      evidence: { field: 'harvestDate' },
      recommendation: 'Provide harvest date for complete customer provenance.',
      confidence: 1.0
    });
  }

  if (!expiryDate) {
    flags.push({
      type: 'TRANSPARENCY_INCOMPLETE',
      severity: 'LOW',
      title: 'Missing expiry date',
      message: 'Expiry date has not been provided.',
      evidence: { field: 'expiryDate' },
      recommendation: 'Provide expected expiry or best-before date.',
      confidence: 1.0
    });
  }

  if (!origin || !String(origin).trim()) {
    flags.push({
      type: 'TRANSPARENCY_INCOMPLETE',
      severity: 'LOW',
      title: 'Missing origin location',
      message: 'Origin has not been provided.',
      evidence: { field: 'origin' },
      recommendation: 'Add farm origin location for customer trust.',
      confidence: 1.0
    });
  }

  if (!batchNumber || !String(batchNumber).trim()) {
    flags.push({
      type: 'TRANSPARENCY_INCOMPLETE',
      severity: 'LOW',
      title: 'Missing batch number',
      message: 'Batch number has not been provided.',
      evidence: { field: 'batchNumber' },
      recommendation: 'Assign a batch number to support traceability.',
      confidence: 1.0
    });
  }

  if (!ingredients || !String(ingredients).trim()) {
    flags.push({
      type: 'TRANSPARENCY_INCOMPLETE',
      severity: 'LOW',
      title: 'Missing ingredients information',
      message: 'Ingredients information has not been provided.',
      evidence: { field: 'ingredients' },
      recommendation: 'Provide ingredient list or single-ingredient confirmation.',
      confidence: 1.0
    });
  }

  return flags;
}

/**
 * 3. Date Anomaly Detector
 * Checks for temporal inconsistencies such as expiry < harvest or packing < harvest.
 */
export function detectDateAnomaly(product) {
  const flags = [];
  if (!product) return flags;

  const transparency = product.transparency || {};
  const rawHarvest = transparency.harvestDate || product.harvestDate;
  const rawPacking = transparency.packingDate || product.packingDate;
  const rawExpiry = transparency.expiryDate || product.expiryDate;

  const hDate = rawHarvest ? new Date(rawHarvest) : null;
  const pDate = rawPacking ? new Date(rawPacking) : null;
  const eDate = rawExpiry ? new Date(rawExpiry) : null;

  // Expiry before harvest
  if (hDate && eDate && !isNaN(hDate.getTime()) && !isNaN(eDate.getTime())) {
    if (eDate < hDate) {
      flags.push({
        type: 'DATE_INCONSISTENCY',
        severity: 'HIGH',
        title: 'Expiry occurs before harvest',
        message: 'Expiry date occurs before harvest date.',
        evidence: {
          harvestDate: hDate.toISOString().split('T')[0],
          expiryDate: eDate.toISOString().split('T')[0]
        },
        recommendation: 'Review and correct harvest and expiry dates.',
        confidence: 1.0
      });
    }
  }

  // Packing before harvest
  if (hDate && pDate && !isNaN(hDate.getTime()) && !isNaN(pDate.getTime())) {
    if (pDate < hDate) {
      flags.push({
        type: 'DATE_INCONSISTENCY',
        severity: 'HIGH',
        title: 'Packing occurs before harvest',
        message: 'Packing date occurs before harvest date.',
        evidence: {
          harvestDate: hDate.toISOString().split('T')[0],
          packingDate: pDate.toISOString().split('T')[0]
        },
        recommendation: 'Ensure packing date occurs on or after harvest date.',
        confidence: 1.0
      });
    }
  }

  // Expiry date already passed
  if (eDate && !isNaN(eDate.getTime())) {
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const expCopy = new Date(eDate);
    expCopy.setHours(0, 0, 0, 0);

    if (expCopy < today) {
      const isActive = product.status === 'ACTIVE';
      flags.push({
        type: 'DATE_INCONSISTENCY',
        severity: isActive ? 'HIGH' : 'MEDIUM',
        title: 'Product expiry passed',
        message: 'Product expiry date has already passed.',
        evidence: {
          expiryDate: eDate.toISOString().split('T')[0],
          productStatus: product.status || 'ACTIVE'
        },
        recommendation: isActive
          ? 'Mark listing as OUT_OF_STOCK or update harvest and expiry dates for the new batch.'
          : 'Review batch record before reactivating listing.',
        confidence: 1.0
      });
    }
  }

  return flags;
}

/**
 * 4. Stock Anomaly Detector
 * Checks for inventory inconsistencies.
 */
export function detectStockAnomaly(product) {
  const flags = [];
  if (!product) return flags;

  const quantity = Number(product.quantity);
  const availableQuantity = Number(product.availableQuantity);

  // Negative total quantity
  if (!isNaN(quantity) && quantity < 0) {
    flags.push({
      type: 'INVENTORY_INCONSISTENCY',
      severity: 'HIGH',
      title: 'Negative total quantity',
      message: 'Total quantity cannot be negative.',
      evidence: { quantity },
      recommendation: 'Correct inventory quantity to a non-negative number.',
      confidence: 1.0
    });
  }

  // Negative available quantity
  if (!isNaN(availableQuantity) && availableQuantity < 0) {
    flags.push({
      type: 'INVENTORY_INCONSISTENCY',
      severity: 'HIGH',
      title: 'Negative available quantity',
      message: 'Available quantity cannot be negative.',
      evidence: { availableQuantity },
      recommendation: 'Ensure available inventory is non-negative.',
      confidence: 1.0
    });
  }

  // Available quantity exceeds total quantity
  if (!isNaN(quantity) && !isNaN(availableQuantity) && quantity >= 0 && availableQuantity > quantity) {
    flags.push({
      type: 'INVENTORY_INCONSISTENCY',
      severity: 'HIGH',
      title: 'Available quantity exceeds total quantity',
      message: 'Available quantity exceeds total quantity.',
      evidence: { quantity, availableQuantity },
      recommendation: 'Align available stock with total inventory quantity.',
      confidence: 1.0
    });
  }

  // Active status with 0 available stock
  if (product.status === 'ACTIVE' && !isNaN(availableQuantity) && availableQuantity === 0) {
    flags.push({
      type: 'INVENTORY_INCONSISTENCY',
      severity: 'MEDIUM',
      title: 'Active product with zero available stock',
      message: 'Product has 0 available quantity while marked as ACTIVE.',
      evidence: { availableQuantity: 0, status: product.status },
      recommendation: 'Update product status to OUT_OF_STOCK or replenish available stock.',
      confidence: 1.0
    });
  }

  return flags;
}

/**
 * 5. Product Data Consistency Detector
 * Checks base field validity.
 */
export function detectDataConsistencyAnomaly(product) {
  const flags = [];
  if (!product) return flags;

  // Price <= 0
  const price = Number(product.price);
  if (isNaN(price) || price <= 0) {
    flags.push({
      type: 'DATA_INCONSISTENCY',
      severity: 'HIGH',
      title: 'Invalid product price',
      message: 'Product price must be greater than zero.',
      evidence: { price: product.price },
      recommendation: 'Set a valid selling price greater than ₹0.',
      confidence: 1.0
    });
  }

  // Missing product name
  if (!product.name || !String(product.name).trim()) {
    flags.push({
      type: 'DATA_INCONSISTENCY',
      severity: 'HIGH',
      title: 'Missing product name',
      message: 'Product name is missing.',
      evidence: { name: product.name || null },
      recommendation: 'Provide a clear, descriptive product name.',
      confidence: 1.0
    });
  }

  // Missing category
  if (!product.category || !String(product.category).trim()) {
    flags.push({
      type: 'DATA_INCONSISTENCY',
      severity: 'HIGH',
      title: 'Missing category',
      message: 'Product category is missing.',
      evidence: { category: product.category || null },
      recommendation: 'Assign a valid product category.',
      confidence: 1.0
    });
  }

  // Missing or invalid unit
  if (!product.unit || !String(product.unit).trim()) {
    flags.push({
      type: 'DATA_INCONSISTENCY',
      severity: 'MEDIUM',
      title: 'Missing product unit',
      message: 'Product unit of measurement is missing or invalid.',
      evidence: { unit: product.unit || null },
      recommendation: 'Select a standard measurement unit (e.g., kg, dozen, bunch).',
      confidence: 1.0
    });
  }

  return flags;
}

/**
 * 6. Image Review Required Detector
 * Safe, lightweight URL format and presence check without external image fetching.
 */
export function detectImageAnomaly(product) {
  const flags = [];
  if (!product) return flags;

  const url = product.imageUrl;

  if (!url || !String(url).trim()) {
    flags.push({
      type: 'IMAGE_REVIEW_REQUIRED',
      severity: 'LOW',
      title: 'Product image missing',
      message: 'Product listing does not include an image.',
      evidence: { imageUrl: null },
      recommendation: 'Upload a product photograph for better consumer trust.',
      confidence: 1.0
    });
    return flags;
  }

  const cleanUrl = String(url).trim().toLowerCase();
  const isValidUrl =
    cleanUrl.startsWith('http://') ||
    cleanUrl.startsWith('https://') ||
    cleanUrl.startsWith('/') ||
    cleanUrl.startsWith('data:image/');

  if (!isValidUrl) {
    flags.push({
      type: 'IMAGE_REVIEW_REQUIRED',
      severity: 'LOW',
      title: 'Unrecognized image URL format',
      message: 'Product image URL is not a standard web URL.',
      evidence: { imageUrl: url },
      recommendation: 'Provide a standard web image URL (http:// or https://).',
      confidence: 0.95
    });
  }

  return flags;
}

/**
 * 7. Verification Risk Signal Detector
 * Non-authoritative risk indicator based on farmer profile verification state.
 * Never mutates farmer profile.
 */
export function detectVerificationRisk(product, farmerProfile) {
  const flags = [];
  if (!farmerProfile) return flags;

  if (!farmerProfile.verified || farmerProfile.verificationStatus === 'PENDING') {
    flags.push({
      type: 'VERIFICATION_RISK',
      severity: 'LOW',
      title: 'Farmer verification pending',
      message: 'Listing is provided by a farmer whose profile verification is still pending.',
      evidence: {
        verified: farmerProfile.verified,
        verificationStatus: farmerProfile.verificationStatus
      },
      recommendation: 'Complete farmer profile verification to establish higher buyer confidence.',
      confidence: 1.0
    });
  }

  return flags;
}

/**
 * 8. AI Explanation Layer
 * Takes structured flags only and produces an explainable summary and recommendations.
 */
export async function explainAnomalyFlags(flags = []) {
  if (!flags || flags.length === 0) {
    return {
      summary: 'No potential anomalies or data inconsistencies were detected.',
      recommendations: [
        'Listing information is complete and consistent with marketplace standards.',
        'Keep inventory and harvest records up to date as batches rotate.'
      ]
    };
  }

  // 1. Try external AI if configured
  const externalResult = await callGeminiVerificationIfConfigured(flags);
  if (externalResult) {
    return externalResult;
  }

  // 2. Deterministic local explanation generator
  const highCount = flags.filter((f) => f.severity === 'HIGH').length;
  const medCount = flags.filter((f) => f.severity === 'MEDIUM').length;
  const lowCount = flags.filter((f) => f.severity === 'LOW').length;

  let severityText = 'minor review recommendations';
  if (highCount > 0) {
    severityText = 'important items requiring attention';
  } else if (medCount > 0) {
    severityText = 'moderate discrepancies to review';
  }

  const issueTitles = flags.map((f, i) => `${i + 1}. ${f.message}`).join(' ');
  const summary = `${flags.length} potential issue${flags.length > 1 ? 's were' : ' was'} detected with ${severityText}. ${issueTitles}`;

  // Deduplicate recommendations
  const uniqueRecs = Array.from(new Set(flags.map((f) => f.recommendation).filter(Boolean)));
  if (uniqueRecs.length === 0) {
    uniqueRecs.push('Review product transparency and pricing information before customer purchase.');
  }

  return {
    summary,
    recommendations: uniqueRecs
  };
}

/**
 * Overall product analysis runner.
 * Combines all detectors and generates advisory review flags.
 * READ-ONLY: Never mutates database.
 */
export async function analyzeProduct(product, { farmerProfile = null, comparableProducts = [] } = {}) {
  const flags = [];

  // 1. Data consistency check
  flags.push(...detectDataConsistencyAnomaly(product));

  // 2. Stock anomaly check
  flags.push(...detectStockAnomaly(product));

  // 3. Price anomaly check (using real MySQL comparables)
  const priceFlag = detectPriceAnomaly(product, comparableProducts);
  if (priceFlag) {
    flags.push(priceFlag);
  }

  // 4. Transparency incomplete check
  flags.push(...detectTransparencyAnomaly(product));

  // 5. Date anomaly check
  flags.push(...detectDateAnomaly(product));

  // 6. Image check
  flags.push(...detectImageAnomaly(product));

  // 7. Verification risk signal
  flags.push(...detectVerificationRisk(product, farmerProfile));

  // Determine overall risk level
  let riskLevel = 'LOW';
  if (flags.some((f) => f.severity === 'HIGH')) {
    riskLevel = 'HIGH';
  } else if (flags.some((f) => f.severity === 'MEDIUM')) {
    riskLevel = 'MEDIUM';
  }

  // AI explanation layer
  const { summary, recommendations } = await explainAnomalyFlags(flags);

  return {
    riskLevel,
    flags,
    summary,
    recommendations,
    checkedAt: new Date().toISOString()
  };
}

/**
 * Farmer portfolio analyzer runner.
 * Analyzes all products of the authenticated farmer.
 * READ-ONLY: Never mutates database.
 */
export async function analyzeFarmer(farmerId) {
  const farmer = await prisma.farmerProfile.findUnique({
    where: { id: farmerId },
    include: {
      products: {
        include: {
          transparency: true
        },
        orderBy: { createdAt: 'desc' }
      }
    }
  });

  if (!farmer) {
    const error = new Error('Farmer profile not found.');
    error.status = 404;
    throw error;
  }

  const products = farmer.products || [];

  // Extract distinct categories to fetch real comparable products
  const categories = Array.from(new Set(products.map((p) => p.category).filter(Boolean)));

  const allCategoryProducts = await prisma.product.findMany({
    where: {
      category: { in: categories },
      status: 'ACTIVE'
    },
    select: {
      id: true,
      category: true,
      price: true,
      unit: true,
      status: true
    }
  });

  const productAnalyses = [];
  let totalFlags = 0;
  let highSeverity = 0;
  let mediumSeverity = 0;
  let lowSeverity = 0;
  let productsRequiringReview = 0;

  for (const product of products) {
    const analysis = await analyzeProduct(product, {
      farmerProfile: farmer,
      comparableProducts: allCategoryProducts
    });

    if (analysis.flags.length > 0) {
      productsRequiringReview++;
    }

    totalFlags += analysis.flags.length;
    for (const flag of analysis.flags) {
      if (flag.severity === 'HIGH') highSeverity++;
      else if (flag.severity === 'MEDIUM') mediumSeverity++;
      else if (flag.severity === 'LOW') lowSeverity++;
    }

    productAnalyses.push({
      product: {
        id: product.id,
        name: product.name,
        category: product.category,
        price: product.price,
        unit: product.unit,
        quantity: product.quantity,
        availableQuantity: product.availableQuantity,
        status: product.status,
        imageUrl: product.imageUrl,
        location: product.location
      },
      riskLevel: analysis.riskLevel,
      flags: analysis.flags,
      summary: analysis.summary,
      recommendations: analysis.recommendations
    });
  }

  let overallRisk = 'LOW';
  if (highSeverity > 0) {
    overallRisk = 'HIGH';
  } else if (mediumSeverity > 0) {
    overallRisk = 'MEDIUM';
  }

  // Summary message
  let summary = `All ${products.length} products analyzed. No high-risk anomalies detected.`;
  if (highSeverity > 0) {
    summary = `Analysis identified ${highSeverity} high-priority item${highSeverity > 1 ? 's' : ''} across ${productsRequiringReview} product${productsRequiringReview > 1 ? 's' : ''} requiring immediate review.`;
  } else if (mediumSeverity > 0) {
    summary = `Analysis identified ${mediumSeverity} moderate item${mediumSeverity > 1 ? 's' : ''} across ${productsRequiringReview} product${productsRequiringReview > 1 ? 's' : ''} recommended for review.`;
  } else if (totalFlags > 0) {
    summary = `Analysis identified ${totalFlags} minor transparency recommendation${totalFlags > 1 ? 's' : ''}.`;
  }

  const recommendations = [
    'Review flagged listings to ensure pricing and transparency data are accurate.',
    'Keep harvest and expiry dates current as batches rotate.',
    'Ensure product availability matches live storage quantities.'
  ];

  return {
    riskLevel: overallRisk,
    totalProducts: products.length,
    productsRequiringReview,
    totalFlags,
    highSeverity,
    mediumSeverity,
    lowSeverity,
    flags: productAnalyses,
    summary,
    recommendations
  };
}
